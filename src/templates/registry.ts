/**
 * ADR 0061 Decision 6 — TemplateSeed shape.
 *
 * `pages[*]` mirrors `CanvasPage` except `sections` becomes `bodyRefs`
 * (pointers into the Section Library). `headerRef` / `footerRef` are
 * site-level pinned slots per ADR 0059.
 */
