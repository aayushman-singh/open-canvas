// ---------------------------------------------------------------------------
// Section pool resolution
//
// Resolve refs against the entire SECTION_LIBRARY by deterministic
// `${baseSlug}-v${version}` id (Phase B's `entryRowId` shape). A miss is
// a build-time bug — fail loud rather than fall back to a placeholder.

const sectionPoolByRowId = new Map<string, (typeof SECTION_LIBRARY)[number]>();
for (const entry of SECTION_LIBRARY) {
  sectionPoolByRowId.set(entryRowId(entry), entry);
}

function resolveRef(ref: SectionInstanceRef): CanvasSection {
  const entry = sectionPoolByRowId.get(ref.sectionId);
  if (!entry) {
    throw new Error(
      `instantiateTemplate: unresolved section ref '${ref.sectionId}' — pool entry missing. ` +
        `Did you remove a ` +
        `SECTION_LIBRARY` +
        ` entry without updating the composition?`,
    );
  }
  // Deep clone so each instantiation gets a fresh tree; overrides + scope
  // never mutate the shared pool entry.
  const section = JSON.parse(JSON.stringify(entry.sectionData)) as CanvasSection;
  section.instanceScope = ref.instanceId;
  if (ref.overrides) {
    for (const [origId, patch] of Object.entries(ref.overrides)) {
      const el = section.elements.find((e) => e.id === origId);
      if (el) Object.assign(el, patch);
    }
  }
  return section;
}

